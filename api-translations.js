export function translateValues(values = []) {
  return values.filter(Boolean).map((value) => TRANSLATIONS[value] ?? value).join(', ');
}

export function translateSeasons(values = []) {
  return values.filter(Boolean).map((value) => value.replace(/^Season (\d+)$/, 'Сезон $1')).join(', ');
}

export function translateBirth(born = '') {
  const years = born.match(/\d+(?=\s*AC)/g);
  const year = years ? `${/or before/i.test(born) ? 'Не позднее ' : ''}${years.join(' или ')} г. от Завоевания Эйгона` : '';
  const place = born.match(/(?:, at |^At )(.+)$/i)?.[1];
  const birthplace = place && place !== 'Unknown' ? (BIRTHPLACES[place] ?? place) : '';
  return [year, birthplace].filter(Boolean).join(', ');
}
